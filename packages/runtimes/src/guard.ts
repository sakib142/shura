/**
 * Shura's gateway for the tools it does not own.
 *
 * A CLI-driven agent reads and writes through Claude Code's own tools, which
 * never reach `McpToolGateway`. Everything the gateway enforced for file I/O —
 * refusing a credential file, refusing a path outside the worktree — would
 * simply stop applying.
 *
 * So the rules are restated as a `PreToolUse` hook the CLI runs before every
 * tool call. Exit 2 blocks the call and sends the reason to the model, which
 * was confirmed against the live CLI: asked to read a `.env` holding a secret,
 * the agent is refused and the secret never enters the transcript.
 *
 * The script is generated per run rather than shipped, for two reasons. It has
 * to know this run's worktree, and it has to carry the patterns from
 * `@shura/core` rather than a second copy of them that can drift. It runs on
 * every tool call, so it is plain node with no imports and no database.
 */

import { realpathSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { SECRET_PATTERNS } from '@shura/core';

/** Tool inputs that name a path, and the key it arrives under. */
const PATH_KEYS = ['file_path', 'notebook_path', 'path'];

export interface GuardOptions {
  /** The worktree. Nothing outside it may be written. */
  readonly workdir: string;
  /** Where to put the generated script. */
  readonly dir: string;
}

/**
 * Writes the hook and returns the settings JSON that installs it.
 *
 * The matcher is `*`: a rule that only covered the tools we thought of would
 * stop covering them the moment the CLI gained another.
 */
export function writeGuard(o: GuardOptions): { settings: string; scriptPath: string } {
  const scriptPath = join(o.dir, 'shura-guard.mjs');
  writeFileSync(scriptPath, guardSource(o.workdir), { mode: 0o700 });

  return {
    scriptPath,
    settings: JSON.stringify({
      hooks: {
        PreToolUse: [
          { matcher: '*', hooks: [{ type: 'command', command: `node ${scriptPath}` }] },
        ],
      },
    }),
  };
}

/** The generated script. Exported so a test can read it without spawning. */
/**
 * Every spelling of the worktree path.
 *
 * On macOS `/var` is a symlink to `/private/var`, and the CLI reports whichever
 * form it resolved — sometimes one, sometimes the other, within a single run.
 * Comparing literally meant the guard refused legitimate writes to its own
 * worktree, and a live builder was denied twice before stumbling onto the
 * spelling that matched.
 */
function spellings(workdir: string): string[] {
  const out = new Set<string>([workdir]);
  try {
    out.add(realpathSync(workdir));
  } catch {
    // The directory may not exist yet; the literal path is still correct.
  }
  return [...out];
}

export function guardSource(workdir: string): string {
  return `#!/usr/bin/env node
// Generated by Shura for one run. Do not edit: it is rewritten every time.
//
// PreToolUse hook. Exit 2 blocks the call and the message on stderr is what
// the agent is told. Exit 0 allows it.
//
// It fails OPEN on its own errors, deliberately. A guard that crashed the run
// on a tool shape it did not recognise would be a worse failure than the one
// it prevents, and the tools it exists to stop are named explicitly.
// The generated file is .mjs, so these are imports rather than require.
import { realpathSync } from 'node:fs';
import { dirname } from 'node:path';

const SECRET = new RegExp(${JSON.stringify(SECRET_PATTERNS.file)}, 'i');
const ALLOWED = new RegExp(${JSON.stringify(SECRET_PATTERNS.exception)}, 'i');
const WORKDIRS = ${JSON.stringify(spellings(workdir))};
const PATH_KEYS = ${JSON.stringify(PATH_KEYS)};

/**
 * Both sides reduced to one canonical form before comparing.
 *
 * Normalising only the worktree was not enough: on macOS the CLI reports a
 * path under /private/var while the worktree is known as /var, and the two
 * never match literally whichever end you fix. The file being written may not
 * exist yet, so this resolves the longest ancestor that does.
 */
function canonical(p) {
  let cur = p;
  for (;;) {
    try {
      return realpathSync(cur) + p.slice(cur.length);
    } catch {
      const parent = dirname(cur);
      if (parent === cur) return p;
      cur = parent;
    }
  }
}

function inside(p) {
  const target = canonical(p);
  return WORKDIRS.some((d) => {
    const base = canonical(d);
    return target === base || target.startsWith(base.endsWith('/') ? base : base + '/');
  });
}

let raw = '';
process.stdin.on('data', (c) => (raw += c));
process.stdin.on('end', () => {
  let call;
  try {
    call = JSON.parse(raw);
  } catch {
    process.exit(0);
  }
  const input = call.tool_input ?? {};

  // Bash reaches the filesystem without naming a path in its input, so the
  // path checks below never see it. A planner holding no Write tool still ran
  // \`npm install\` and wrote node_modules, which is harmless — but the same
  // shell could have read a credential file, and that is not.
  //
  // This is not a sandbox and does not pretend to be one: a shell is
  // Turing-complete and an agent set on evading this would. It stops the
  // accident, which is the failure that actually happened — an agent reading a
  // committed .env while exploring. The real boundaries remain the worktree,
  // the push guard, and the read-only sandbox on the reviewing side.
  if (call.tool_name === 'Bash' && typeof input.command === 'string') {
    // Split on anything that is not a path character. Deliberately NOT a
    // whitespace class: this source is inside a template literal, and an
    // escaped \\s there silently became a literal "s" — the guard split on the
    // letter and matched almost nothing, while looking like it worked.
    for (const word of input.command.split(/[^A-Za-z0-9._/-]+/)) {
      if (word === '' || ALLOWED.test(word)) continue;
      if (SECRET.test(word)) {
        process.stderr.write(
          'That command names a file holding credentials, which Shura does not let an agent ' +
            'read. If you need to know what configuration the project expects, read its ' +
            'example file (.env.example) instead.'
        );
        process.exit(2);
      }
    }
  }

  for (const key of PATH_KEYS) {
    const path = input[key];
    if (typeof path !== 'string' || path === '') continue;

    if (!ALLOWED.test(path) && SECRET.test(path)) {
      process.stderr.write(
        'This file holds credentials and Shura does not let an agent read it. ' +
          'If you need to know what configuration the project expects, read its ' +
          'example file (.env.example) instead.'
      );
      process.exit(2);
    }

    // Writing outside the worktree. Reads are left alone: an agent may
    // legitimately read a system header or a dependency, and the worktree is
    // where the damage would be done.
    const writes = call.tool_name === 'Write' || call.tool_name === 'Edit' ||
      call.tool_name === 'NotebookEdit';
    if (writes && path.startsWith('/') && !inside(path)) {
      process.stderr.write(
        'That path is outside the checked-out repository, which is the only place ' +
          'this task may change. Work inside ' + WORKDIRS[0] + '.'
      );
      process.exit(2);
    }
  }
  process.exit(0);
});
`;
}
